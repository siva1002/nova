"""Builds each service's baseline migration SQL from the database design in tools/db-split.

  python tools/make_baselines.py

For every service:  _prelude.sql + <service>.sql + _epilogue.sql  ->  services/<svc>/migrations/sql/0001_baseline.sql
(_prelude = shared functions and the outbox/inbox tables; _epilogue = forced row-level security and grants.)
Phase-1 tables only; the *.later.sql files (parked tables) are NOT included.
Run it only BEFORE the first real deploy. After that, schema changes are new forward migrations.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "db-split"
SERVICES = ["identity", "access", "hierarchy", "tasks", "time"]

for svc in SERVICES:
    parts = [SRC / "_prelude.sql", SRC / f"{svc}.sql", SRC / "_epilogue.sql"]
    body = "\n\n".join(f"-- ===== {p.name} =====\n" + p.read_text(encoding="utf-8") for p in parts)
    out = ROOT / "services" / svc / "migrations" / "sql" / "0001_baseline.sql"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(f"-- GENERATED by tools/make_baselines.py. Do not edit.\n{body}\n", encoding="utf-8", newline="\n")
    print(f"{svc}: {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")
